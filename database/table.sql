1. TABLA: USUARIOS

CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    auth_uid UUID UNIQUE
        REFERENCES auth.users(id) ON DELETE CASCADE,

    nombre_usuario VARCHAR(100) NOT NULL,
    apellido_usuario VARCHAR(100) NOT NULL,

    email_usuario VARCHAR(100) NOT NULL UNIQUE,
    dni_usuario VARCHAR(15) UNIQUE,
    telefono_usuario VARCHAR(30),

    rol_usuario VARCHAR(20) NOT NULL DEFAULT 'usuario'
        CHECK (rol_usuario IN (
            'usuario',
            'entrenador',
            'administrador'
        )),

    saldo_usuario DECIMAL(10,2) NOT NULL DEFAULT 0.00
        CHECK (saldo_usuario >= 0),

    estado_usuario BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);



CREATE TABLE IF NOT EXISTS public.administradores (
    id_administrador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INT NOT NULL UNIQUE
        REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,

    nivel_acceso VARCHAR(30) NOT NULL DEFAULT 'Principal',

    permiso_config BOOLEAN NOT NULL DEFAULT TRUE
);



CREATE TABLE IF NOT EXISTS public.entrenadores (
    id_entrenador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INT NOT NULL UNIQUE
        REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,

    especialidad_entrenador VARCHAR(100) NOT NULL,

    estado_entrenador BOOLEAN NOT NULL DEFAULT TRUE
);



CREATE TABLE IF NOT EXISTS public.actividades (
    id_actividad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre_actividad VARCHAR(100) NOT NULL,

    descripcion_actividad TEXT,

    categoria_actividad VARCHAR(80),

    dia_actividad VARCHAR(100) NOT NULL,

    hora_inicio TIME NOT NULL,

    hora_fin TIME NOT NULL,

    cupo_maximo INT NOT NULL
        CHECK (cupo_maximo > 0),

    id_entrenador INT
        REFERENCES public.entrenadores(id_entrenador)
        ON DELETE SET NULL,

    lugar_actividad VARCHAR(120),

    estado_actividad BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (hora_fin > hora_inicio)
);



CREATE TABLE IF NOT EXISTS public.inscripciones (
    id_inscripcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INT NOT NULL
        REFERENCES public.usuarios(id_usuario)
        ON DELETE CASCADE,

    id_actividad INT NOT NULL
        REFERENCES public.actividades(id_actividad)
        ON DELETE CASCADE,

    fecha_inscripcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    estado_inscripcion VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_inscripcion IN (
            'pendiente',
            'aprobada',
            'rechazada',
            'cancelada'
        )),

    observaciones TEXT,

    UNIQUE (id_usuario, id_actividad)
);



CREATE TABLE IF NOT EXISTS public.pagos (
    id_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INT NOT NULL
        REFERENCES public.usuarios(id_usuario),

    id_inscripcion INT
        REFERENCES public.inscripciones(id_inscripcion)
        ON DELETE SET NULL,

    concepto_pago VARCHAR(100) NOT NULL,

    monto_pago DECIMAL(10,2) NOT NULL
        CHECK (monto_pago > 0),

    medio_pago VARCHAR(30)
        CHECK (medio_pago IN (
            'efectivo',
            'transferencia',
            'tarjeta',
            'otro'
        )),

    fecha_pago TIMESTAMPTZ,

    estado_pago VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_pago IN (
            'pendiente',
            'aprobado',
            'rechazado',
            'anulado'
        )),

    referencia_pago VARCHAR(120),

    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE TABLE IF NOT EXISTS public.movimientos (
    id_movimiento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_usuario INT NOT NULL
        REFERENCES public.usuarios(id_usuario),

    id_pago INT
        REFERENCES public.pagos(id_pago)
        ON DELETE SET NULL,

    descripcion_movimiento VARCHAR(150) NOT NULL,

    monto_movimiento DECIMAL(10,2) NOT NULL,

    tipo_movimiento VARCHAR(20) NOT NULL
        CHECK (tipo_movimiento IN (
            'ingreso',
            'egreso',
            'ajuste'
        )),

    fecha_mov TIMESTAMPTZ NOT NULL DEFAULT NOW()
);



CREATE TABLE IF NOT EXISTS public.sesiones_actividad (
    id_sesion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_actividad INT NOT NULL
        REFERENCES public.actividades(id_actividad)
        ON DELETE CASCADE,

    fecha_sesion DATE NOT NULL,

    hora_inicio TIME NOT NULL,

    hora_fin TIME NOT NULL,

    observaciones TEXT,

    estado_sesion VARCHAR(20) NOT NULL DEFAULT 'programada'
        CHECK (estado_sesion IN (
            'programada',
            'realizada',
            'cancelada'
        )),

    CHECK (hora_fin > hora_inicio)
);



CREATE TABLE IF NOT EXISTS public.asistencias (
    id_asistencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_inscripcion INT NOT NULL
        REFERENCES public.inscripciones(id_inscripcion)
        ON DELETE CASCADE,

    id_sesion INT NOT NULL
        REFERENCES public.sesiones_actividad(id_sesion)
        ON DELETE CASCADE,

    id_entrenador INT NOT NULL
        REFERENCES public.entrenadores(id_entrenador),

    estado_asistencia VARCHAR(20) NOT NULL
        CHECK (estado_asistencia IN (
            'presente',
            'ausente'
        )),

    observaciones TEXT,

    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (id_inscripcion, id_sesion)
);



CREATE INDEX IF NOT EXISTS idx_inscripciones_usuario
ON public.inscripciones(id_usuario);

CREATE INDEX IF NOT EXISTS idx_inscripciones_actividad
ON public.inscripciones(id_actividad);

CREATE INDEX IF NOT EXISTS idx_pagos_usuario
ON public.pagos(id_usuario);

CREATE INDEX IF NOT EXISTS idx_pagos_estado
ON public.pagos(estado_pago);

CREATE INDEX IF NOT EXISTS idx_movimientos_usuario
ON public.movimientos(id_usuario);

CREATE INDEX IF NOT EXISTS idx_actividades_entrenador
ON public.actividades(id_entrenador);

CREATE INDEX IF NOT EXISTS idx_sesiones_fecha
ON public.sesiones_actividad(fecha_sesion);

CREATE INDEX IF NOT EXISTS idx_asistencias_sesion
ON public.asistencias(id_sesion);